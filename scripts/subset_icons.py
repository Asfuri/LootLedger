"""Subset the Material Symbols font to the icons the app uses (15 MB -> 17 KB).

    python scripts/subset_icons.py MaterialSymbolsRounded.ttf

Get the font from https://github.com/google/material-design-icons (variablefont folder). Needs fontTools
(pip install fonttools). Writes crates/app/ui/icons.ttf and crates/app/ui/icons.slint, where
each icon is a string holding its codepoint, so no ligature shaping is needed at run time.
"""
from pathlib import Path
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[1]
NAMES = """
all_inclusive today date_range calendar_month sports_esports query_stats trophy schedule timer list_alt
play_circle trending_up category tune grid_on workspace_premium groups broken_image health_and_safety timelapse
flag compare_arrows check_circle error expand_more expand_less add remove close drag_indicator dashboard
dashboard_customize refresh ios_share picture_in_picture_alt settings palette folder folder_open keyboard database
download upload undo star search filter_list arrow_back arrow_forward arrow_upward arrow_downward check open_in_new
sensors insights inventory_2 open_in_full close_fullscreen table_view data_object edit delete restore_from_trash
chevron_left chevron_right info history volume_up content_copy help backup restart_alt visibility bar_chart person
favorite bolt sync lock celebration military_tech
""".split()


def main():
    font = TTFont(sys.argv[1])
    best = font.getBestCmap()
    glyph_to_code = {}
    for code, glyph in best.items():
        glyph_to_code.setdefault(glyph, code)
    codes = {}
    for name in NAMES:
        glyph = name  # the font names each icon glyph after the icon
        if glyph not in glyph_to_code:
            raise SystemExit(f"Unknown icon or icon without a codepoint: {name}")
        codes[name] = glyph_to_code[glyph]
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(codes.values()))
    subsetter.subset(font)
    # Slint cannot set variation axes: keep the default outlined style only.
    font = instancer.instantiateVariableFont(font, {"FILL": 0, "wght": 400, "GRAD": 0, "opsz": 24})
    out = ROOT / "crates/app/ui/icons.ttf"
    font.save(out)
    lines = ["// Generated by scripts/subset_icons.py from Material Symbols Rounded (Apache 2.0).",
             'import "icons.ttf";', "", "export global Icons {",
             '    out property <string> family: "Material Symbols Rounded";']
    lines += [f'    out property <string> {name.replace("_", "-")}: "\\u{{{code:x}}}";' for name, code in codes.items()]
    lines.append("}")
    (ROOT / "crates/app/ui/icons.slint").write_text("\n".join(lines) + "\n", encoding="utf-8")
    rust = ["//! Generated by scripts/subset_icons.py: Material Symbols names and their codepoints.", "",
            "pub fn glyph(name: &str) -> &'static str {", "    match name {"]
    rust += [f'        "{name}" => "\\u{{{code:x}}}",' for name, code in codes.items()]
    rust += ['        _ => "",', "    }", "}"]
    (ROOT / "crates/app/src/icons.rs").write_text("\n".join(rust) + "\n", encoding="utf-8")
    print(f"{len(codes)} icons, {out.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
